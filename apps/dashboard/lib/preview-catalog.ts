import reelLayout from "../reel-layout.json";
import type { StoredConfig } from "@/lib/schema";

export const PREVIEW_CASES = ["1-line", "2-line", "3-line"] as const;
export type PreviewCase = typeof PREVIEW_CASES[number];
export type PreviewSample = PreviewCase | "2-line-comparison";
export const DEFAULT_PREVIEW_CASE: PreviewCase = "2-line";
export const PREVIEW_CATALOG_DIRECTORY = "v3";
export const PREVIEW_CATALOG_MANIFEST_FILENAME = "workspace.json";
export const PREVIEW_CATALOG_MANIFEST_URL = "/previews/v3/workspace.json";
export const PREVIEW_ARABIC_GAPS = [80, 100, 120] as const;
export const PREVIEW_LAYOUT_COUNT = 19620;

export interface PreviewGlyph {
  image: string;
  left_offset: number;
  right_offset: number;
  top_offset: number;
  bottom_offset: number;
  line_count: number;
  visual_line_ranges: [number, number][];
}
export interface PreviewLayout {
  anchor_x: number;
  glyphs: string[];
  tops: number[];
  backing: [number, number, number, number];
  bottom: number;
}
export interface PreviewCatalogManifest {
  version: 3;
  canvas: [1080, 1920];
  header_top: number;
  safe_zone: { x: number; y: number; right: number; bottom: number; width: number; height: number };
  overlay_darkness: number;
  subtitle_center: number;
  safe_bottom: number;
  samples: { id: PreviewSample; label: string; arabic: string; en: string; de: string; source: string }[];
  glyphs: Record<string, PreviewGlyph>;
  layouts: Record<string, PreviewLayout>;
  headers: Record<string, string>;
  colors: Record<string, string>;
  files: Record<string, string>;
}

/** All pixel positions are generated by calculate_multilingual_subtitle_group_layout. */
export function buildPreviewCatalogKey(config: StoredConfig, previewCase: PreviewSample): string {
  return [previewCase, config.arabic_font_size, config.translation_font_size,
    config.arabic_translation_gap_px, config.translation_languages.join("-"),
    config.translation_languages.length === 2 ? config.translation_stack_gap_px : 0].join("/");
}

export function selectPreview(manifest: PreviewCatalogManifest, config: StoredConfig, previewCase: PreviewSample) {
  const key = buildPreviewCatalogKey(config, previewCase);
  const layout = manifest.layouts[key];
  // The production header without backing is identical to the plain-text raster.
  const noBacking = config.header_backing_intensity === "none";
  const headerStyle = noBacking && config.header_style !== "hidden" ? "plain_text" : config.header_style;
  const header = manifest.headers[[previewCase, config.header_content, config.ayah_reference_position,
    headerStyle, noBacking ? "low" : config.header_backing_intensity].join("/")];
  const sample = manifest.samples.find(s => s.id === previewCase);
  if (!layout || !header || !sample) throw new Error("This layout is missing from the static preview. Regenerate the catalog.");
  const glyphs = layout.glyphs.map(key => manifest.glyphs[key]);
  if (glyphs.some(glyph => !glyph)) throw new Error("Static preview text assets are incomplete.");
  const lineLimits = [config.arabic_max_lines, ...config.translation_languages.map(language =>
    language === "de" ? reelLayout.translationMaxLines.de : config.translation_max_lines
  )];
  const exceedsLines = glyphs.some((glyph, index) => glyph.visual_line_ranges.length > lineLimits[index]);
  return { key, layout, header, sample, glyphs, exceedsLines };
}

export function validatePreviewManifest(value: unknown): PreviewCatalogManifest {
  const m = value as PreviewCatalogManifest;
  if (!m || m.version !== 3 || m.canvas?.[0] !== reelLayout.width || m.canvas?.[1] !== reelLayout.height
    || m.safe_zone?.x !== reelLayout.safeZone.left || m.safe_zone?.y !== reelLayout.safeZone.top
    || m.safe_zone?.right !== reelLayout.width - reelLayout.safeZone.right
    || m.safe_zone?.bottom !== reelLayout.height - reelLayout.safeZone.bottom
    || m.safe_zone?.width !== reelLayout.width - reelLayout.safeZone.left - reelLayout.safeZone.right
    || m.safe_zone?.height !== reelLayout.height - reelLayout.safeZone.top - reelLayout.safeZone.bottom
    || typeof m.overlay_darkness !== "number" || m.overlay_darkness < 0 || m.overlay_darkness > 1
    || !m.layouts || Object.keys(m.layouts).length !== PREVIEW_LAYOUT_COUNT
    || !m.glyphs || Object.values(m.glyphs).some(g => !Array.isArray(g.visual_line_ranges) || !g.visual_line_ranges.length)
    || !m.headers || !m.files || m.samples?.map(s => s.id).join(",") !== [...PREVIEW_CASES, "2-line-comparison"].join(",")) {
    throw new Error("Static preview catalog is incomplete or has the wrong version.");
  }
  return m;
}

export async function loadPreviewCatalog(fetcher: typeof fetch = fetch) {
  const response = await fetcher(PREVIEW_CATALOG_MANIFEST_URL, { cache: "no-cache" });
  if (!response.ok) throw new Error(`Static preview could not be loaded (${response.status}).`);
  return validatePreviewManifest(await response.json());
}
