-- Record the replacement only after normal ingestion has supplied two valid,
-- immutable assessments and advanced a remediated ledger entry to SCREENED.
create or replace function public.editorial_record_technical_schema_rescreen()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $editorial_record_technical_schema_rescreen$
declare
  v_invalidation public.editorial_screening_remediation_events%rowtype;
begin
  if old.screening_status <> 'SCREENED' and new.screening_status = 'SCREENED' then
    select e.* into v_invalidation
      from public.editorial_screening_remediation_events e
     where e.policy_version = new.policy_version
       and e.surah_number = new.surah_number
       and e.ayah_number = new.ayah_number
       and e.event_type = 'TECHNICAL_SCHEMA_INVALIDATED'
       and not exists (
         select 1
           from public.editorial_screening_remediation_events replacement
          where replacement.policy_version = e.policy_version
            and replacement.surah_number = e.surah_number
            and replacement.ayah_number = e.ayah_number
            and replacement.event_type = 'TECHNICAL_SCHEMA_RESCREENED'
            and replacement.prior_evidence_fingerprint = e.prior_evidence_fingerprint
       )
     order by e.occurred_at desc
     limit 1;

    if found then
      insert into public.editorial_screening_remediation_events (
        policy_version, surah_number, ayah_number, event_type,
        prior_run_id, prior_evidence_fingerprint,
        replacement_run_id, replacement_evidence_fingerprint,
        reason, actor, details
      ) values (
        new.policy_version, new.surah_number, new.ayah_number,
        'TECHNICAL_SCHEMA_RESCREENED',
        v_invalidation.prior_run_id, v_invalidation.prior_evidence_fingerprint,
        new.screening_run_id, new.evidence_fingerprint,
        'NORMAL_STRICT_DUAL_REVIEW_INGEST',
        coalesce(nullif(current_setting('app.editorial_actor', true), ''), 'database'),
        jsonb_build_object(
          'assessment_version', new.assessment_version,
          'semantic_assessment', new.semantic_assessment,
          'screened_at', new.screened_at
        )
      );
    end if;
  end if;
  return new;
end;
$editorial_record_technical_schema_rescreen$;

revoke all on function public.editorial_record_technical_schema_rescreen()
  from public, anon, authenticated;

drop trigger if exists editorial_record_technical_schema_rescreen_trigger
  on public.editorial_ayah_reviews;
create trigger editorial_record_technical_schema_rescreen_trigger
after update of screening_status, screening_run_id, evidence_fingerprint
on public.editorial_ayah_reviews
for each row execute function public.editorial_record_technical_schema_rescreen();

create or replace function public.invalidate_technical_editorial_schema_fallbacks(
  p_policy_version text,
  p_records jsonb,
  p_actor text
) returns jsonb
language plpgsql
security invoker
set search_path = pg_catalog, public
as $invalidate_technical_editorial_schema_fallbacks$
declare
  v_record jsonb;
  v_review public.editorial_ayah_reviews%rowtype;
  v_surah_number integer;
  v_ayah_number integer;
  v_expected_run_id text;
  v_expected_fingerprint text;
  v_key text;
  v_seen text[] := '{}';
  v_invalidated integer := 0;
  v_already_invalidated integer := 0;
begin
  if p_policy_version <> 'calm-inviting-v1'
     or coalesce(length(trim(p_actor)), 0) = 0
     or jsonb_typeof(p_records) <> 'array'
     or jsonb_array_length(p_records) not between 1 and 50 then
    raise exception 'invalid technical editorial remediation request';
  end if;

  perform set_config('app.editorial_actor', trim(p_actor), true);

  for v_record in select value from jsonb_array_elements(p_records)
  loop
    if jsonb_typeof(v_record) <> 'object'
       or (select count(*) from jsonb_object_keys(v_record)) <> 4
       or not (v_record ?& array['surah_number', 'ayah_number', 'expected_run_id', 'expected_evidence_fingerprint'])
       or jsonb_typeof(v_record->'surah_number') <> 'number'
       or jsonb_typeof(v_record->'ayah_number') <> 'number'
       or jsonb_typeof(v_record->'expected_run_id') <> 'string'
       or jsonb_typeof(v_record->'expected_evidence_fingerprint') <> 'string' then
      raise exception 'invalid technical editorial remediation record';
    end if;

    v_surah_number := (v_record->>'surah_number')::integer;
    v_ayah_number := (v_record->>'ayah_number')::integer;
    v_expected_run_id := v_record->>'expected_run_id';
    v_expected_fingerprint := v_record->>'expected_evidence_fingerprint';
    v_key := v_surah_number::text || ':' || v_ayah_number::text;
    if v_key = any(v_seen) or v_expected_fingerprint !~ '^[0-9a-f]{64}$'
       or coalesce(length(trim(v_expected_run_id)), 0) = 0 then
      raise exception 'duplicate or invalid technical editorial remediation identity: %', v_key;
    end if;
    v_seen := array_append(v_seen, v_key);

    select * into v_review
      from public.editorial_ayah_reviews r
     where r.policy_version = p_policy_version
       and r.surah_number = v_surah_number
       and r.ayah_number = v_ayah_number
     for update;
    if not found then
      raise exception 'technical editorial remediation identity is not canonical: %', v_key;
    end if;

    if v_review.screening_status = 'NOT_SCREENED'
       and exists (
         select 1 from public.editorial_screening_remediation_events e
          where e.policy_version = p_policy_version
            and e.surah_number = v_surah_number
            and e.ayah_number = v_ayah_number
            and e.event_type = 'TECHNICAL_SCHEMA_INVALIDATED'
            and e.prior_run_id = v_expected_run_id
            and e.prior_evidence_fingerprint = v_expected_fingerprint
       ) then
      v_already_invalidated := v_already_invalidated + 1;
      continue;
    end if;

    if v_review.screening_status <> 'SCREENED'
       or v_review.semantic_assessment <> 'AMBIGUOUS_REVIEW_REQUIRED'
       or v_review.screening_run_id is distinct from v_expected_run_id
       or v_review.evidence_fingerprint is distinct from v_expected_fingerprint then
      raise exception 'review is not the expected technical fallback: %', v_key;
    end if;

    if exists (
      select 1 from public.editorial_production_authorizations p
       where p.policy_version = $1
         and p.surah_number = v_surah_number
         and p.ayah_number = v_ayah_number
         and p.authorization_state = 'ACTIVE'
    ) then
      raise exception 'technical remediation refuses an actively authorized identity: %', v_key;
    end if;

    if not exists (
      select 1
        from public.editorial_ayah_assessments a
       where a.run_id = v_review.screening_run_id
         and a.policy_version = v_review.policy_version
         and a.surah_number = v_review.surah_number
         and a.ayah_number = v_review.ayah_number
       group by a.run_id, a.policy_version, a.surah_number, a.ayah_number
      having count(*) = 2
         and count(distinct a.pass_number) = 2
         and bool_and(
           a.assessment_rationale like 'Fail-closed schema repair:%'
           or a.evidence #> '{_evaluator_audit,normalized_for_ingest}' = 'true'::jsonb
         )
    ) then
      raise exception 'review does not have exactly two historical technical fallback assessments: %', v_key;
    end if;

    insert into public.editorial_screening_remediation_events (
      policy_version, surah_number, ayah_number, event_type,
      prior_run_id, prior_evidence_fingerprint, reason, actor, details
    ) values (
      p_policy_version, v_surah_number, v_ayah_number,
      'TECHNICAL_SCHEMA_INVALIDATED',
      v_review.screening_run_id, v_review.evidence_fingerprint,
      'MALFORMED_REVIEW_SCHEMA', trim(p_actor),
      jsonb_build_object(
        'prior_semantic_assessment', v_review.semantic_assessment,
        'prior_assessment_version', v_review.assessment_version,
        'prior_screened_at', v_review.screened_at
      )
    );

    update public.editorial_ayah_reviews
       set screening_status = 'NOT_SCREENED',
           semantic_assessment = null,
           screening_theme = null,
           assessment_rationale = null,
           context_notes = null,
           source_hash = null,
           translation_hash = null,
           assessment_version = null,
           evaluator_version = null,
           screening_run_id = null,
           screening_failure_reason = 'TECHNICAL_REVIEW_SCHEMA_INVALIDATED',
           evidence_fingerprint = null,
           screened_at = null,
           updated_at = clock_timestamp()
     where policy_version = p_policy_version
       and surah_number = v_surah_number
       and ayah_number = v_ayah_number;
    v_invalidated := v_invalidated + 1;
  end loop;

  return jsonb_build_object(
    'invalidated', v_invalidated,
    'already_invalidated', v_already_invalidated,
    'requested', jsonb_array_length(p_records)
  );
end;
$invalidate_technical_editorial_schema_fallbacks$;

revoke all on function public.invalidate_technical_editorial_schema_fallbacks(text, jsonb, text)
  from public, anon, authenticated;
grant execute on function public.invalidate_technical_editorial_schema_fallbacks(text, jsonb, text)
  to service_role;
