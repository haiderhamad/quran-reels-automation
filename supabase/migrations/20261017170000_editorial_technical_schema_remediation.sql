-- Append-only remediation for legacy records whose malformed native reviews
-- were previously shaped into semantic ambiguity.  The old assessment rows,
-- source evidence, audit rows, and batch records are never rewritten.
--
-- This is intentionally a narrow integrity repair, not a semantic decision:
-- only records that carry the documented technical-fallback signature may be
-- returned to NOT_SCREENED.  They must subsequently pass the normal strict
-- dual-review ingestion path before becoming SCREENED again.

create table if not exists public.editorial_screening_remediation_events (
  event_id bigint generated by default as identity primary key,
  policy_version text not null,
  surah_number integer not null,
  ayah_number integer not null,
  event_type text not null check (
    event_type in ('TECHNICAL_SCHEMA_INVALIDATED', 'TECHNICAL_SCHEMA_RESCREENED')
  ),
  prior_run_id text not null,
  prior_evidence_fingerprint text not null check (prior_evidence_fingerprint ~ '^[0-9a-f]{64}$'),
  replacement_run_id text,
  replacement_evidence_fingerprint text check (replacement_evidence_fingerprint is null or replacement_evidence_fingerprint ~ '^[0-9a-f]{64}$'),
  reason text not null,
  actor text not null,
  details jsonb not null default '{}'::jsonb check (jsonb_typeof(details) = 'object'),
  occurred_at timestamptz not null default now(),
  foreign key (policy_version, surah_number, ayah_number)
    references public.editorial_ayah_reviews (policy_version, surah_number, ayah_number),
  check (
    (event_type = 'TECHNICAL_SCHEMA_INVALIDATED'
      and replacement_run_id is null and replacement_evidence_fingerprint is null)
    or
    (event_type = 'TECHNICAL_SCHEMA_RESCREENED'
      and replacement_run_id is not null and replacement_evidence_fingerprint is not null)
  ),
  unique (policy_version, surah_number, ayah_number, event_type, prior_evidence_fingerprint)
);

create index if not exists editorial_screening_remediation_events_lookup_idx
  on public.editorial_screening_remediation_events
    (policy_version, surah_number, ayah_number, occurred_at desc);

alter table public.editorial_screening_remediation_events enable row level security;
revoke all on table public.editorial_screening_remediation_events from public, anon, authenticated;
grant select, insert on table public.editorial_screening_remediation_events to service_role;
drop policy if exists editorial_screening_remediation_events_service_role_only
  on public.editorial_screening_remediation_events;
create policy editorial_screening_remediation_events_service_role_only
  on public.editorial_screening_remediation_events
  for all to service_role
  using (true)
  with check (true);

