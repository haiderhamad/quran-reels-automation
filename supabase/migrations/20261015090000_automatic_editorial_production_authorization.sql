-- Automatic production authorization for the calm-inviting editorial policy.
--
-- A completed, dual-pass ELIGIBLE_CANDIDATE assessment is the production
-- decision.  This migration records that decision durably, preserves the
-- existing active legacy catalog, and exposes only technically valid,
-- non-revoked exact passage ranges to production workers.

create table if not exists public.editorial_production_authorizations (
  authorization_id bigint generated by default as identity primary key,
  policy_version text not null,
  surah_number integer not null,
  ayah_number integer not null,
  passage_first_ayah integer not null,
  passage_last_ayah integer not null,
  approval_basis text not null check (approval_basis in ('LEGACY_CATALOG', 'SCREENING_ELIGIBLE')),
  assessment_version text,
  source_hash text,
  translation_hash text,
  evidence_fingerprint text,
  screening_run_id text,
  authorization_state text not null default 'ACTIVE' check (authorization_state in ('ACTIVE', 'REVOKED')),
  authorization_reason text not null,
  authorized_at timestamptz not null default now(),
  revoked_at timestamptz,
  revoked_by text,
  revocation_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint editorial_production_authorizations_bounds_check
    check (passage_first_ayah <= ayah_number and ayah_number <= passage_last_ayah),
  constraint editorial_production_authorizations_auto_evidence_check check (
    approval_basis <> 'SCREENING_ELIGIBLE'
    or (
      assessment_version is not null and btrim(assessment_version) <> ''
      and source_hash ~ '^[0-9a-f]{64}$'
      and translation_hash ~ '^[0-9a-f]{64}$'
      and evidence_fingerprint ~ '^[0-9a-f]{64}$'
      and screening_run_id is not null and btrim(screening_run_id) <> ''
    )
  ),
  constraint editorial_production_authorizations_revocation_check check (
    (authorization_state = 'ACTIVE' and revoked_at is null and revoked_by is null and revocation_reason is null)
    or (authorization_state = 'REVOKED' and revoked_at is not null and revoked_by is not null and revocation_reason is not null)
  ),
  constraint editorial_production_authorizations_identity_unique
    unique (policy_version, surah_number, ayah_number, approval_basis)
);

create index if not exists editorial_production_authorizations_active_idx
  on public.editorial_production_authorizations (policy_version, authorization_state, surah_number, passage_first_ayah, passage_last_ayah);

create table if not exists public.editorial_production_authorization_events (
  event_id bigint generated by default as identity primary key,
  authorization_id bigint not null references public.editorial_production_authorizations (authorization_id),
  event_type text not null check (event_type in ('AUTO_AUTHORIZED', 'LEGACY_IMPORTED', 'REVOKED')),
  actor text not null,
  details jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create index if not exists editorial_production_authorization_events_authorization_idx
  on public.editorial_production_authorization_events (authorization_id, occurred_at);

create or replace function public.editorial_validate_production_authorization()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $editorial_validate_authorization$
begin
  if not exists (
    select 1 from public.editorial_canonical_ayahs
    where surah_number = new.surah_number and ayah_number = new.ayah_number
  ) then
    raise exception 'Production authorization identity is not canonical: %:%', new.surah_number, new.ayah_number;
  end if;

  if not exists (
    select 1 from public.editorial_canonical_ayahs
    where surah_number = new.surah_number and ayah_number = new.passage_first_ayah
  ) or not exists (
    select 1 from public.editorial_canonical_ayahs
    where surah_number = new.surah_number and ayah_number = new.passage_last_ayah
  ) then
    raise exception 'Production authorization passage bounds are not canonical: %:%-%', new.surah_number, new.passage_first_ayah, new.passage_last_ayah;
  end if;

  if tg_op = 'UPDATE' and old.approval_basis = 'SCREENING_ELIGIBLE' and (
    new.policy_version,
    new.surah_number,
    new.ayah_number,
    new.passage_first_ayah,
    new.passage_last_ayah,
    new.assessment_version,
    new.source_hash,
    new.translation_hash,
    new.evidence_fingerprint,
    new.screening_run_id
  ) is distinct from (
    old.policy_version,
    old.surah_number,
    old.ayah_number,
    old.passage_first_ayah,
    old.passage_last_ayah,
    old.assessment_version,
    old.source_hash,
    old.translation_hash,
    old.evidence_fingerprint,
    old.screening_run_id
  ) then
    raise exception 'Automatic screening authorization evidence is immutable';
  end if;

  new.updated_at := now();
  return new;
end;
$editorial_validate_authorization$;

drop trigger if exists editorial_validate_production_authorization_trigger
  on public.editorial_production_authorizations;
create trigger editorial_validate_production_authorization_trigger
before insert or update on public.editorial_production_authorizations
for each row execute function public.editorial_validate_production_authorization();

create or replace function public.editorial_record_production_authorization_event()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $editorial_authorization_event$
begin
  if tg_op = 'INSERT' then
    insert into public.editorial_production_authorization_events (
      authorization_id, event_type, actor, details
    ) values (
      new.authorization_id,
      case when new.approval_basis = 'SCREENING_ELIGIBLE' then 'AUTO_AUTHORIZED' else 'LEGACY_IMPORTED' end,
      case when new.approval_basis = 'SCREENING_ELIGIBLE' then 'editorial-screening-policy' else 'legacy-catalog-import' end,
      jsonb_build_object(
        'policy_version', new.policy_version,
        'canonical_key', new.surah_number::text || ':' || new.ayah_number::text,
        'passage_first_ayah', new.passage_first_ayah,
        'passage_last_ayah', new.passage_last_ayah,
        'approval_basis', new.approval_basis,
        'assessment_version', new.assessment_version,
        'evidence_fingerprint', new.evidence_fingerprint
      )
    );
  elsif old.authorization_state = 'ACTIVE' and new.authorization_state = 'REVOKED' then
    insert into public.editorial_production_authorization_events (
      authorization_id, event_type, actor, details
    ) values (
      new.authorization_id,
      'REVOKED',
      new.revoked_by,
      jsonb_build_object('reason', new.revocation_reason)
    );
  end if;
  return new;
end;
$editorial_authorization_event$;

drop trigger if exists editorial_record_production_authorization_event_trigger
  on public.editorial_production_authorizations;
create trigger editorial_record_production_authorization_event_trigger
after insert or update of authorization_state on public.editorial_production_authorizations
for each row execute function public.editorial_record_production_authorization_event();

-- This runs after the ingestion RPC has inserted both immutable assessment
-- rows and committed the reconciled review row.  It does not re-evaluate
-- meaning; the authoritative semantic decision remains the existing final
-- ELIGIBLE_CANDIDATE classification.
create or replace function public.editorial_auto_authorize_eligible_screening()
returns trigger
language plpgsql
set search_path = pg_catalog, public
as $editorial_auto_authorize$
declare
  v_first integer;
  v_last integer;
begin
  if new.screening_status <> 'SCREENED'
     or new.semantic_assessment <> 'ELIGIBLE_CANDIDATE'
     or new.assessment_version is null
     or new.source_hash is null
     or new.translation_hash is null
     or new.evidence_fingerprint is null
     or new.screening_run_id is null then
    return new;
  end if;

  select
    (a.evidence->>'passage_first_ayah')::integer,
    (a.evidence->>'passage_last_ayah')::integer
  into v_first, v_last
  from public.editorial_ayah_assessments a
  where a.run_id = new.screening_run_id
    and a.policy_version = new.policy_version
    and a.surah_number = new.surah_number
    and a.ayah_number = new.ayah_number
    and a.pass_number = 1
    and a.semantic_assessment = 'ELIGIBLE_CANDIDATE';

  if v_first is null or v_last is null then
    return new;
  end if;

  insert into public.editorial_production_authorizations (
    policy_version, surah_number, ayah_number, passage_first_ayah, passage_last_ayah,
    approval_basis, assessment_version, source_hash, translation_hash,
    evidence_fingerprint, screening_run_id, authorization_reason
  ) values (
    new.policy_version, new.surah_number, new.ayah_number, v_first, v_last,
    'SCREENING_ELIGIBLE', new.assessment_version, new.source_hash, new.translation_hash,
    new.evidence_fingerprint, new.screening_run_id,
    'Automatic authorization from two-pass final ELIGIBLE_CANDIDATE screening classification.'
  ) on conflict (policy_version, surah_number, ayah_number, approval_basis) do nothing;

  return new;
end;
$editorial_auto_authorize$;

drop trigger if exists editorial_auto_authorize_eligible_screening_trigger
  on public.editorial_ayah_reviews;
create trigger editorial_auto_authorize_eligible_screening_trigger
after update of screening_status, semantic_assessment, assessment_version, source_hash,
  translation_hash, evidence_fingerprint, screening_run_id
on public.editorial_ayah_reviews
for each row execute function public.editorial_auto_authorize_eligible_screening();

-- Keep the established legacy catalog intact as a first-class authorization
-- source.  Each ayah in a legacy range receives the exact original range.
with active_catalog as (
  select a.policy_version, c.release_id, c.manifest_sha256, c.manifest
  from public.editorial_active_catalog a
  join public.editorial_catalog_releases c
    on c.policy_version = a.policy_version and c.release_id = a.release_id
), legacy_ranges as (
  select
    a.policy_version,
    a.release_id,
    a.manifest_sha256,
    (r.value->>'surah')::integer as surah_number,
    (r.value->>'first_ayah')::integer as passage_first_ayah,
    (r.value->>'last_ayah')::integer as passage_last_ayah
  from active_catalog a
  cross join lateral jsonb_array_elements(a.manifest->'ranges') as r(value)
), legacy_ayahs as (
  select
    r.policy_version,
    r.release_id,
    r.manifest_sha256,
    r.surah_number,
    gs.ayah_number,
    r.passage_first_ayah,
    r.passage_last_ayah
  from legacy_ranges r
  cross join lateral generate_series(r.passage_first_ayah, r.passage_last_ayah) as gs(ayah_number)
)
insert into public.editorial_production_authorizations (
  policy_version, surah_number, ayah_number, passage_first_ayah, passage_last_ayah,
  approval_basis, evidence_fingerprint, authorization_reason
)
select
  policy_version, surah_number, ayah_number, passage_first_ayah, passage_last_ayah,
  'LEGACY_CATALOG', manifest_sha256,
  'Preserved active legacy catalog authorization: ' || release_id
from legacy_ayahs
on conflict (policy_version, surah_number, ayah_number, approval_basis) do nothing;

-- Backfill the existing final eligible decisions without asking the evaluator
-- to repeat a semantic assessment.
insert into public.editorial_production_authorizations (
  policy_version, surah_number, ayah_number, passage_first_ayah, passage_last_ayah,
  approval_basis, assessment_version, source_hash, translation_hash,
  evidence_fingerprint, screening_run_id, authorization_reason
)
select
  r.policy_version,
  r.surah_number,
  r.ayah_number,
  (a.evidence->>'passage_first_ayah')::integer,
  (a.evidence->>'passage_last_ayah')::integer,
  'SCREENING_ELIGIBLE',
  r.assessment_version,
  r.source_hash,
  r.translation_hash,
  r.evidence_fingerprint,
  r.screening_run_id,
  'Automatic authorization backfill from existing two-pass final ELIGIBLE_CANDIDATE screening classification.'
from public.editorial_ayah_reviews r
join public.editorial_ayah_assessments a
  on a.run_id = r.screening_run_id
 and a.policy_version = r.policy_version
 and a.surah_number = r.surah_number
 and a.ayah_number = r.ayah_number
 and a.pass_number = 1
where r.screening_status = 'SCREENED'
  and r.semantic_assessment = 'ELIGIBLE_CANDIDATE'
  and a.semantic_assessment = 'ELIGIBLE_CANDIDATE'
on conflict (policy_version, surah_number, ayah_number, approval_basis) do nothing;

-- A row is production-authorized only while its backing data remains
-- technically complete and intact.  This intentionally validates evidence,
-- identities and bounds without introducing another semantic review stage.
create or replace view public.editorial_production_authorized_ayahs
with (security_invoker = true)
as
with valid_automatic as (
  select p.*
  from public.editorial_production_authorizations p
  join public.editorial_ayah_reviews r
    on r.policy_version = p.policy_version
   and r.surah_number = p.surah_number
   and r.ayah_number = p.ayah_number
  join lateral (
    select
      count(*) as pass_count,
      count(distinct a.pass_number) as distinct_pass_count,
      count(*) filter (where a.pass_number in (1, 2)) as required_pass_count,
      count(*) filter (where a.semantic_assessment = 'ELIGIBLE_CANDIDATE') as eligible_pass_count,
      count(*) filter (where a.source_hash = p.source_hash and a.translation_hash = p.translation_hash) as source_match_count,
      count(*) filter (where a.evidence->>'passage_first_ayah' = p.passage_first_ayah::text
                         and a.evidence->>'passage_last_ayah' = p.passage_last_ayah::text) as bounds_match_count,
      count(*) filter (where jsonb_typeof(a.evidence->'passage_first_ayah') = 'number'
                         and jsonb_typeof(a.evidence->'passage_last_ayah') = 'number'
                         and jsonb_typeof(a.evidence->'standalone_sufficient') = 'boolean'
                         and jsonb_typeof(a.evidence->'context_keys') = 'array'
                         and a.evidence->'context_keys' ? (p.surah_number::text || ':' || p.ayah_number::text)
                         and jsonb_typeof(a.evidence->'exclusion_indicators') = 'array'
                         and jsonb_array_length(a.evidence->'exclusion_indicators') = 0
                         and a.evidence->>'uncertainty' = 'clear') as valid_evidence_count,
      count(distinct a.evidence->'context_keys') as distinct_context_count,
      count(distinct a.evidence->>'prompt_sha256') as distinct_prompt_count,
      count(*) filter (where a.evidence->>'prompt_sha256' ~ '^[0-9a-f]{64}$') as valid_prompt_count
    from public.editorial_ayah_assessments a
    where a.run_id = p.screening_run_id
      and a.policy_version = p.policy_version
      and a.surah_number = p.surah_number
      and a.ayah_number = p.ayah_number
  ) assessment on true
  where p.approval_basis = 'SCREENING_ELIGIBLE'
    and p.authorization_state = 'ACTIVE'
    and r.screening_status = 'SCREENED'
    and r.semantic_assessment = 'ELIGIBLE_CANDIDATE'
    and r.assessment_version = p.assessment_version
    and r.source_hash = p.source_hash
    and r.translation_hash = p.translation_hash
    and r.evidence_fingerprint = p.evidence_fingerprint
    and r.screening_run_id = p.screening_run_id
    and exists (
      select 1 from public.editorial_source_evidence s
      where s.policy_version = p.policy_version
        and s.surah_number = p.surah_number
        and s.ayah_number = p.ayah_number
        and s.source_hash = p.source_hash
        and s.translation_hash = p.translation_hash
    )
    and assessment.pass_count = 2
    and assessment.distinct_pass_count = 2
    and assessment.required_pass_count = 2
    and assessment.eligible_pass_count = 2
    and assessment.source_match_count = 2
    and assessment.bounds_match_count = 2
    and assessment.valid_evidence_count = 2
    and assessment.distinct_context_count = 1
    and assessment.distinct_prompt_count = 2
    and assessment.valid_prompt_count = 2
), valid_legacy as (
  select p.*
  from public.editorial_production_authorizations p
  where p.approval_basis = 'LEGACY_CATALOG'
    and p.authorization_state = 'ACTIVE'
    and exists (
      select 1 from public.editorial_canonical_ayahs c
      where c.surah_number = p.surah_number and c.ayah_number = p.ayah_number
    )
    and exists (
      select 1 from public.editorial_canonical_ayahs c
      where c.surah_number = p.surah_number and c.ayah_number = p.passage_first_ayah
    )
    and exists (
      select 1 from public.editorial_canonical_ayahs c
      where c.surah_number = p.surah_number and c.ayah_number = p.passage_last_ayah
    )
)
select * from valid_legacy
union all
select * from valid_automatic;

create or replace view public.editorial_production_authorized_passages
with (security_invoker = true)
as
select
  policy_version,
  surah_number,
  passage_first_ayah,
  passage_last_ayah,
  array_agg(authorization_id order by authorization_id) as authorization_ids,
  array_agg(distinct approval_basis order by approval_basis) as approval_bases,
  array_agg(distinct (surah_number::text || ':' || ayah_number::text) order by (surah_number::text || ':' || ayah_number::text)) as candidate_ayah_keys,
  md5(string_agg(authorization_id::text, ',' order by authorization_id)) as authorization_fingerprint
from public.editorial_production_authorized_ayahs
group by policy_version, surah_number, passage_first_ayah, passage_last_ayah;

create or replace function public.get_production_authorized_passages(p_policy_version text)
returns table (
  policy_version text,
  surah_number integer,
  passage_first_ayah integer,
  passage_last_ayah integer,
  authorization_ids bigint[],
  approval_bases text[],
  candidate_ayah_keys text[],
  authorization_fingerprint text
)
language sql
stable
set search_path = pg_catalog, public
as $editorial_authorized_passages$
  select
    policy_version,
    surah_number,
    passage_first_ayah,
    passage_last_ayah,
    authorization_ids,
    approval_bases,
    candidate_ayah_keys,
    authorization_fingerprint
  from public.editorial_production_authorized_passages
  where policy_version = p_policy_version
  order by surah_number, passage_first_ayah, passage_last_ayah;
$editorial_authorized_passages$;

-- Keep the existing worker summary contract and make its production figure a
-- distinct union of legacy and automatic authorizations.
create or replace view public.editorial_screening_worker_summary
with (security_invoker = true)
as
with approval_counts as (
  select
    policy_version,
    count(distinct (surah_number, ayah_number))::integer as production_approved_ayahs,
    count(distinct (surah_number, ayah_number)) filter (where approval_basis = 'SCREENING_ELIGIBLE')::integer as automatic_production_approved_ayahs,
    count(distinct (surah_number, ayah_number)) filter (where approval_basis = 'LEGACY_CATALOG')::integer as legacy_production_approved_ayahs
  from public.editorial_production_authorized_ayahs
  group by policy_version
), passage_counts as (
  select policy_version, count(*)::integer as production_approved_passages
  from public.editorial_production_authorized_passages
  group by policy_version
)
select
  r.policy_version,
  count(*)::integer as canonical_ayahs,
  count(*) filter (where r.screening_status = 'SCREENED')::integer as screened_ayahs,
  count(*) filter (where r.screening_status <> 'SCREENED')::integer as not_screened_ayahs,
  count(*) filter (where r.semantic_assessment = 'ELIGIBLE_CANDIDATE')::integer as eligible_candidates,
  count(*) filter (where r.semantic_assessment = 'INELIGIBLE_CANDIDATE')::integer as ineligible_candidates,
  count(*) filter (where r.semantic_assessment = 'AMBIGUOUS_REVIEW_REQUIRED')::integer as ambiguous_candidates,
  coalesce(a.production_approved_ayahs, 0)::integer as production_approved_ayahs,
  max(r.screened_at) as last_successful_screening_at,
  coalesce(a.automatic_production_approved_ayahs, 0)::integer as automatic_production_approved_ayahs,
  coalesce(a.legacy_production_approved_ayahs, 0)::integer as legacy_production_approved_ayahs,
  coalesce(p.production_approved_passages, 0)::integer as production_approved_passages
from public.editorial_ayah_reviews r
left join approval_counts a on a.policy_version = r.policy_version
left join passage_counts p on p.policy_version = r.policy_version
group by r.policy_version, a.production_approved_ayahs, a.automatic_production_approved_ayahs,
  a.legacy_production_approved_ayahs, p.production_approved_passages;

